#!/usr/bin/env node
// Exports ABIs and deployment info into packages/shared.
//   cd packages/contracts && forge build && node script/export.mjs
// - packages/shared/src/abi/<Contract>.ts   (export const <contract>Abi = [...] as const)
// - packages/shared/src/deployments/42431.json + 42431.ts (addresses + labeled tx hashes from broadcast/)
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shared = join(root, "..", "shared", "src");
const CONTRACTS = ["FXOracleAdapter", "CollateralVault", "LocalStableFactory", "SwapDesk", "CreditPool"];
// v2 (src/v2): [contract, abi export base name]
const CONTRACTS_V2 = [
  ["MultiCollateralVault", "multiCollateralVault"],
  ["MoveAMM", "moveAmm"],
  ["StakedOUSD", "stakedOusd"],
  ["DemoRWA", "demoRwa"],
  ["AdminPriceFeed", "priceFeed"],
  ["MercadoFactoryV2", "mercadoFactoryV2"],
];
const EXTRA = [["ITIP20", "tip20"]]; // Tempo TIP-20 precompile interface (from tempo-std)

const camel = (n) => n.replace(/^[A-Z]+(?=[A-Z][a-z])|^[A-Z]/, (m) => m.toLowerCase());
const header = "// Generated by packages/contracts/script/export.mjs. Do not edit.\n";

// ---------------------------------------------------------------- ABIs
mkdirSync(join(shared, "abi"), { recursive: true });
const abiExports = [];
for (const [name, base] of [...CONTRACTS.map((c) => [c, camel(c)]), ...CONTRACTS_V2, ...EXTRA]) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const file = name === "ITIP20" ? "TIP20" : name;
  writeFileSync(
    join(shared, "abi", `${file}.ts`),
    `${header}export const ${base}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  abiExports.push(`export { ${base}Abi } from "./${file}";`);
}
writeFileSync(join(shared, "abi", "index.ts"), header + abiExports.join("\n") + "\n");

// ---------------------------------------------------------------- deployments
for (const file of readdirSync(join(root, "deployments")).filter((f) => /^\d+\.json$/.test(f))) {
  const chainId = file.replace(".json", "");
  const addrs = JSON.parse(readFileSync(join(root, "deployments", file), "utf8"));
  const bdir = join(root, "broadcast", "Deploy.s.sol", chainId);
  const txs = {};
  let deployedAt;
  const stages = ["core", "smoke", "swap", "credit", "stress"];
  for (const stage of stages) {
    const f =
      stage === "stress"
        ? join(root, "broadcast", "StressDemo.s.sol", chainId, "run-latest.json")
        : join(bdir, `${stage}-latest.json`);
    if (!existsSync(f)) continue;
    const run = JSON.parse(readFileSync(f, "utf8"));
    if (stage === "core") deployedAt = new Date(run.timestamp).toISOString();
    const seen = {};
    for (const tx of run.transactions) {
      const what = tx.transactionType === "CREATE" ? `deploy${tx.contractName}` : tx.function.split("(")[0];
      let label = `${stage}.${what}`;
      seen[label] = (seen[label] ?? 0) + 1;
      if (seen[label] > 1) label += `#${seen[label]}`;
      txs[label] = tx.hash;
    }
  }
  const out = { ...addrs, chainId: Number(chainId), deployedAt, txs };
  // v2 lives alongside v1 under "v2" (crew/V2-DESIGN.md §5b)
  const v2file = join(root, "deployments", `${chainId}.v2.json`);
  if (existsSync(v2file)) {
    const a = JSON.parse(readFileSync(v2file, "utf8"));
    const v2txs = {};
    let v2At;
    for (const stage of ["core", "seed", "credit"]) {
      const f = join(root, "broadcast", "DeployV2.s.sol", chainId, `${stage}-latest.json`);
      if (!existsSync(f)) continue;
      const run = JSON.parse(readFileSync(f, "utf8"));
      if (stage === "core") v2At = new Date(run.timestamp).toISOString();
      const seen = {};
      for (const tx of run.transactions) {
        const what = tx.transactionType === "CREATE" ? `deploy${tx.contractName}` : tx.function.split("(")[0];
        let label = `${stage}.${what}`;
        seen[label] = (seen[label] ?? 0) + 1;
        if (seen[label] > 1) label += `#${seen[label]}`;
        v2txs[label] = tx.hash;
      }
    }
    out.v2 = {
      xMXN: a.xMXN, factory: a.factory, vault: a.vault, vamm: a.vamm, creditPool: a.creditPool, fxOracle: a.fxOracle,
      collaterals: [
        { symbol: "OUSD", token: a.ousd, feed: a.ousdFeed, demo: false, label: "Testnet OUSD (Tempo faucet, no real value)" },
        { symbol: "sOUSD", token: a.sOUSD, feed: a.sOUSDFeed, demo: true, label: "Demo staked OUSD (mock yield, testnet)" },
        { symbol: "tTBILL", token: a.tTBILL, feed: a.tTBILLFeed, demo: true, label: "Demo tokenized T-bill (testnet, not a security)" },
      ],
      attestationSigner: addrs.attestationSigner, merchant: addrs.merchant,
      deployedAt: v2At, txs: v2txs,
    };
  }
  mkdirSync(join(shared, "deployments"), { recursive: true });
  writeFileSync(join(shared, "deployments", `${chainId}.json`), JSON.stringify(out, null, 2) + "\n");
  writeFileSync(
    join(shared, "deployments", `${chainId}.ts`),
    `${header}export const deployment${chainId} = ${JSON.stringify(out, null, 2)} as const;\n`,
  );
  console.log(`deployments/${chainId}: ${Object.keys(txs).length} txs`);
}
const ids = readdirSync(join(shared, "deployments")).filter((f) => /^\d+\.ts$/.test(f)).map((f) => f.replace(".ts", ""));
writeFileSync(
  join(shared, "deployments", "index.ts"),
  header +
    ids.map((id) => `import { deployment${id} } from "./${id}";`).join("\n") +
    `\n\nexport { ${ids.map((id) => `deployment${id}`).join(", ")} };\n` +
    `export const deployments = { ${ids.map((id) => `${id}: deployment${id}`).join(", ")} } as const;\n` +
    `/** Tempo Moderato (42431) deployment. */\nexport const moderatoDeployment = deployment42431;\n`,
);
console.log(`abi: ${abiExports.length} files`);
